"""Generate local development secrets and config files (never committed).

Creates deploy/local/.env with random test credentials, renders the Keycloak realm and the Redis ACL file.
Run once; re-running keeps the existing .env so local databases stay valid. Use --reset to regenerate.
Development only: in Kubernetes environments these values come from Vault (ADR-0022).
"""
import json
import secrets
import string
import sys
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENV_FILE = HERE / ".env"

KEYS = [
    "WAVER_DB_PASSWORD",
    "KEYCLOAK_ADMIN_PASSWORD",
    "VAULT_DEV_ROOT_TOKEN",
    "CONTROL_BFF_CLIENT_SECRET",
    "IDENTITY_SVC_CLIENT_SECRET",
    "WAVER_ADMIN_PASSWORD",
    "REDIS_CONTROL_BFF_PASSWORD",
    "REDIS_EDGE_GATEWAY_PASSWORD",
    "PARTNER_BFF_CLIENT_SECRET",
    "RESELLER_SVC_CLIENT_SECRET",
    "REDIS_PARTNER_BFF_PASSWORD",
]


def random_secret(length: int = 24) -> str:
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(length))


def load_env() -> dict:
    values = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.startswith("#"):
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip()
    return values


def ensure_env(reset: bool) -> dict:
    values = {} if reset else load_env()
    for key in KEYS:
        values.setdefault(key, random_secret())
    values.setdefault("WAVER_PLATFORM_ORG_ID", str(uuid.uuid4()))
    lines = ["# Generated by deploy/local/init.py - local development test values only. Do not commit."]
    lines += [f"{k}={v}" for k, v in values.items()]
    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return values


def render_realm(values: dict) -> None:
    template = (HERE / "keycloak" / "realm-waver.template.json").read_text(encoding="utf-8")
    # The WAVER claims (org_id, org_type, roles, audience) are the same for every client: defined once.
    mappers = (HERE / "keycloak" / "claim-mappers.json").read_text(encoding="utf-8")
    template = template.replace('"__WAVER_CLAIM_MAPPERS__"', mappers.strip())
    for key, value in values.items():
        template = template.replace("${" + key + "}", value)
    json.loads(template)  # fail fast on invalid JSON
    out = HERE / "keycloak" / "generated"
    out.mkdir(exist_ok=True)
    (out / "realm-waver.json").write_text(template, encoding="utf-8")


def render_redis_acl(values: dict) -> None:
    # One ACL user per service, limited to its own key prefix (ADR-0020). The default user is disabled.
    acl = [
        "user default off",
        f"user control-bff on >{values['REDIS_CONTROL_BFF_PASSWORD']} ~waver:sess:control-bff:* &* +@all -@dangerous +info",
        f"user partner-bff on >{values['REDIS_PARTNER_BFF_PASSWORD']} ~waver:sess:partner-bff:* &* +@all -@dangerous +info",
        f"user edge-gateway on >{values['REDIS_EDGE_GATEWAY_PASSWORD']} ~request_rate_limiter.* &* +@all -@dangerous +info",
    ]
    out = HERE / "redis" / "generated"
    out.mkdir(parents=True, exist_ok=True)
    (out / "users.acl").write_text("\n".join(acl) + "\n", encoding="utf-8")


def main() -> None:
    values = ensure_env(reset="--reset" in sys.argv)
    render_realm(values)
    render_redis_acl(values)
    print(f"Wrote {ENV_FILE.relative_to(HERE.parent.parent)} and generated Keycloak/Redis config.")
    print("Login user: admin@waver.local (password in deploy/local/.env, key WAVER_ADMIN_PASSWORD)")


if __name__ == "__main__":
    main()
